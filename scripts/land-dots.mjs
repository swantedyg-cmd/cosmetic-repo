// Builds src/data/landDots.ts: a grid of [lat, lng] points that fall on land,
// for the dotted globe on the ingredients page. Run: node scripts/land-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const STEP = 2.2; // degrees between rows
const dots = [];
for (let lat = -58; lat <= 80; lat += STEP) {
  // Fewer dots per row towards the poles so spacing stays even on the sphere.
  const n = Math.max(1, Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)));
  for (let i = 0; i < n; i++) {
    const lng = -180 + (i / n) * 360;
    if (geoContains(land, [lng, lat])) dots.push(Math.round(lat * 10) / 10, Math.round(lng * 10) / 10);
  }
}
writeFileSync(
  "src/data/landDots.ts",
  `// Generated by scripts/land-dots.mjs from Natural Earth (public domain) via world-atlas. Do not edit.\n// Flat pairs: lat, lng, lat, lng, ...\nexport const LAND_DOTS = new Float32Array([${dots.join(",")}]);\n`,
);
console.log(dots.length / 2, "dots");
